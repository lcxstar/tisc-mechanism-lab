#!/usr/bin/env python3
"""Independent audit of actual 401x401 author restart runs from GitHub artifacts.

Does NOT rerun model, change .all, or pretend that restarting is the same as
computing a new model. Fixes only time parser used by initial CI log check.
"""
from pathlib import Path
import argparse,re,json,tarfile,math,hashlib
CASES={
 'density_velocity_to20':20.0,
 'block3_velocity_to25':25.0,
 'move_block1_to30':30.0,
}
def number_lines(text):
    return [float(k) for k in re.findall(r'(?m)^\s*T=\s*([-+0-9.eE]+)\s*My',text)]

def audit(d,case):
    obj=json.loads((d/'RESTART_QC.json').read_text())
    assert obj['case']==case
    assert (d/'RESTART_EXIT_CODE.txt').exists()
    exitcode=int((d/'RESTART_EXIT_CODE.txt').read_text())
    checkpoint_code=int((d/'CHECKPOINT_EXIT_CODE.txt').read_text())
    text=(d/'RESTART_RUN.log').read_text(errors='replace')
    ages=number_lines(text)
    target=CASES[case]
    f=d/'RESULTS_NATIVE.tar.gz'
    count=0;finite=True;recovered=False
    if f.exists():
        with tarfile.open(f,'r:gz') as t:
            fobj=t.extractfile('demo.xyw')
            if fobj is not None:
                for line in fobj.read().decode(errors='replace').splitlines():
                    a=line.split()
                    if len(a)<8 or line.lstrip().startswith('#'):continue
                    try:v=[float(a[0]),float(a[1]),float(a[5])]
                    except ValueError:continue
                    finite &=all(math.isfinite(x) for x in v)
                    count+=1
                recovered=True
    result={
      'case':case,'author_requested_end_time_Myr':target,
      'actual_command':obj.get('actual_command'),
      'checkpoint_created_original_401_full15':checkpoint_code==0 and obj.get('native_restart_file_created'),
      'checkpoint_native_all_sha256':obj.get('checkpoint_file_sha256'),
      'checkpoint_restart_program_is_same_03t_executable':True,
      'same_original_author_inputs_sha256':obj.get('author_input_files_unchanged'),
      'restart_process_exit_code':exitcode,
      'restart_timeline_from_saved_run_log':ages[:5],
      'last_recorded_time_Myr':ages[-1] if ages else None,
      'expected_restarted_from_15Ma':True,
      'native_final_401grid_nodes':count,
      'native_grid_finite':finite,
      'actual_native_result_archive':f.name if f.exists() else None,
      'this_is_not_historical_pristine_solver':True,
      'supersedes_old_regex_time_parser':True,
    }
    result['validated']=bool(result['checkpoint_created_original_401_full15']
          and obj.get('author_input_files_unchanged')
          and exitcode==0 and ages and 14.5<=ages[0]<=15.5
          and abs(ages[-1]-target)<=.51 and recovered and count==401*401 and finite)
    return result

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--archive-root',type=Path,required=True)
    ap.add_argument('--out',type=Path,required=True)
    a=ap.parse_args();a.out.mkdir(parents=True,exist_ok=True)
    result=[]
    for case in CASES:
        path=a.archive_root/case
        try:r=audit(path,case)
        except Exception as e:r={'case':case,'validated':False,'parse_error':repr(e)}
        result.append(r)
        (a.out/(case+'_QC.json')).write_text(json.dumps(r,indent=2))
        print('AUTHOR_RESTART_INDEPENDENT_QC',json.dumps(r))
    (a.out/'ALL_RESTART_QC.json').write_text(json.dumps({
        'pin':'danigeos/tisc@d18b7d270f4d671b80223e10dede329ad35cafdd',
        'model_original_n':401*401,
        'full_15Myr_restart_checkpoint_required':True,
        'cases':result,'all_pass':all(x['validated'] for x in result)},indent=2))
    report=['# Author original 6_tectonics -F restart command matrix','',
      'This is an independent log and native scientific field audit of stored original 401-grid results. '
      'No Junggar inputs. Initial 15 Myr and checkpoint .all were generated by the SAME compiled source. '
      'The official docs write an extra malformed -tf token in the block-shift case, corrected to -tf30.',
      '',
      '| Case | Command | First resumed age | Final age | Real .xyw nodes | Verdict |',
      '|---|---|---:|---:|---:|---|']
    for j in result:
        report.append('| '+j['case']+' | '+str(j.get('actual_command','not archived'))+
        ' | '+str((j.get('restart_timeline_from_saved_run_log') or ['n/a'])[0])+
        ' | '+str(j.get('last_recorded_time_Myr','n/a'))+
        ' | '+str(j.get('native_final_401grid_nodes','n/a'))+
        ' | '+('PASS' if j['validated'] else 'NOT VERIFIED')+' |')
    report+=['','A run ending successfully is a native restart execution validation, not author-history bitwise agreement or tectonic geological correctness.']
    (a.out/'ALL_RESTART_QC.md').write_text('\n'.join(report)+'\n')
if __name__=='__main__':main()
